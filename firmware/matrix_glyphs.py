"""PlatformIO pre-build script: converts xscreensaver's large xmatrix glyph
sheets (matrix1, matrix2) into the deflated blobs xmatrix.c includes as
images/gen/<name>_png.h (see src/x11shim/include/ximage-loader.h for the
format) and puts them on the include path. The images are read from vendor/
and never committed. Needs uv, because Pillow is not in PlatformIO's Python.

xmatrix.c also includes the small sheets (matrix1b, matrix2b), which it draws
only on a screen under 300 pixels or with `*matrixFont: small`. Their headers
name the large sheets instead, saving their flash (issue #102)."""

import os
import shutil
import subprocess
import sys
from pathlib import Path

Import("env")  # noqa: F821

repo = Path(env["PROJECT_DIR"]).parent  # noqa: F821
images = repo / "vendor" / "xscreensaver-6.16" / "hacks" / "images"
converter = repo / "tools" / "make_logo_blob.py"
generated = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821

for name in ("matrix1", "matrix2"):
    image = images / f"{name}.png"
    header = generated / "images" / "gen" / f"{name}_png.h"
    if not image.is_file():
        sys.exit(f"{image} is missing: run `uv run tools/fetch_xscreensaver.py`")
    if (
        header.exists()
        and header.stat().st_mtime >= image.stat().st_mtime
        and header.stat().st_mtime >= converter.stat().st_mtime
    ):
        continue
    uv = shutil.which("uv")
    if not uv:
        raise SystemExit(
            "matrix_glyphs.py needs uv on PATH to convert the glyph sheets"
        )
    header.parent.mkdir(parents=True, exist_ok=True)
    # Written beside the header and renamed, so a killed build never leaves a
    # truncated header that the mtime check above would trust.
    partial = header.with_name(header.name + ".partial")
    partial.unlink(missing_ok=True)
    subprocess.run(
        [
            uv,
            "run",
            str(converter),
            str(image),
            "--name",
            f"{name}_png",
            "--deflate",
            "-o",
            str(partial),
        ],
        check=True,
    )
    os.replace(partial, header)

for name in ("matrix1", "matrix2"):
    stub = generated / "images" / "gen" / f"{name}b_png.h"
    text = (
        "/* Generated by firmware/matrix_glyphs.py; do not edit. The small\n"
        " * sheet is left out of the build: this names the large one. */\n"
        f"#define {name}b_png {name}_png\n"
    )
    if not stub.exists() or stub.read_text() != text:
        stub.write_text(text)

env.Append(CPPPATH=[str(generated)])  # noqa: F821
