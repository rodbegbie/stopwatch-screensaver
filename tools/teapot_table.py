"""Writes a deflated copy of the Utah teapot table for the device (issue #104).

xscreensaver's glx/teapot2.h is 56,880 floats: 227 KB of flash for a piece
Pipes draws on about 2% of its joints. This writes, into a build directory, a
replacement teapot2.h holding the same floats as one zlib stream, and beside it
an unchanged copy of glx/teapot.c, whose quoted #include "teapot2.h" then finds
the replacement first. firmware/src/glshim/glx_teapot.c unpacks the table while
unit_teapot runs. Neither copied file is edited.

Run with: python3 tools/teapot_table.py <teapot.c> <teapot2.h> <out-dir>
"""

import re
import struct
import sys
import zlib
from pathlib import Path


def parse_floats(text: str) -> list[float]:
    match = re.search(r"teapot_triangles\[\]\s*=\s*\{(.*?)\};", text, re.DOTALL)
    if not match:
        raise ValueError("no teapot_triangles[] table found")
    return [float(t) for t in re.split(r"[\s,]+", match.group(1)) if t]


def render_header(values: list[float], source: str) -> str:
    if len(values) % 9:
        raise ValueError(
            f"{len(values)} floats is not a multiple of 9 (whole triangles)"
        )
    # struct rounds each double to float as C does for a GLfloat initialiser.
    stream = zlib.compress(struct.pack(f"<{len(values)}f", *values), 9)
    rows = [
        "  " + ", ".join(f"0x{b:02x}" for b in stream[i : i + 12]) + ","
        for i in range(0, len(stream), 12)
    ]
    return "\n".join(
        [
            f"/* Generated by tools/teapot_table.py from {source}; do not edit.",
            " * The table as one zlib stream of little-endian floats, unpacked by",
            " * glshim/glx_teapot.c while unit_teapot runs. */",
            f"#define XSHIM_TEAPOT_FLOATS {len(values)}",
            "const GLfloat (*xshim_teapot_table(void))[XSHIM_TEAPOT_FLOATS];",
            "#define teapot_triangles (*xshim_teapot_table())",
            "static const unsigned char teapot_triangles_z[] = {",
            *rows,
            "};",
            "",
        ]
    )


def write_if_changed(path: Path, data: bytes) -> None:
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    teapot_c, teapot2_h, out = Path(argv[0]), Path(argv[1]), Path(argv[2])
    header = render_header(parse_floats(teapot2_h.read_text()), teapot2_h.name)
    out.mkdir(parents=True, exist_ok=True)
    write_if_changed(out / "teapot.c", teapot_c.read_bytes())
    write_if_changed(out / "teapot2.h", header.encode())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
