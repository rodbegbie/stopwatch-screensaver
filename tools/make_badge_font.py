"""Rasterise a pixel TrueType font into an M5GFX GFXfont for the name badge.

M5GFX draws a GFXfont (Adafruit's layout) at any whole-number text size, so a
1-bit font keeps its hard pixel edges when the badge is scaled up. Each glyph
for printable ASCII (32 to 126) is drawn here once at the font's own pixel
size, thresholded to 1 bit and packed from the high bit, row by row, starting
on a byte boundary.

Run with: uv run tools/make_badge_font.py vendor/pixChicago.ttf \\
    --name pix_chicago --size 8 -o pix_chicago.h
"""

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126


def open_font(path: Path, size: int):
    try:
        return ImageFont.truetype(str(path), size, layout_engine=ImageFont.Layout.BASIC)
    except OSError as err:
        raise ValueError(f"{path}: not a usable font ({err})") from err


def check_range(value: int, low: int, high: int, what: str, ch: str) -> int:
    if not low <= value <= high:
        raise ValueError(f"{what} {value} of {ch!r} does not fit GFXglyph")
    return value


def build_glyph(font, ch: str, size: int, bitmap: bytearray) -> dict:
    """Render ch tightly cropped to 1 bit, appending its packed rows to bitmap."""
    advance = check_range(round(font.getlength(ch)), 0, 255, "advance", ch)
    canvas = Image.new("L", (size * 3, size * 3), 0)
    draw = ImageDraw.Draw(canvas)
    draw.fontmode = "1"
    draw.text((size, size * 2), ch, fill=255, font=font, anchor="ls")
    box = canvas.getbbox()
    if box is None:
        return {
            "w": 0,
            "h": 0,
            "x_offset": 0,
            "y_offset": 0,
            "advance": advance,
            "offset": 0,
        }
    left, upper, right, lower = box
    w, h = right - left, lower - upper
    check_range(w, 0, 255, "width", ch)
    check_range(h, 0, 255, "height", ch)
    bits = [
        1 if canvas.getpixel((x, y)) else 0
        for y in range(upper, lower)
        for x in range(left, right)
    ]
    bits += [0] * (-len(bits) % 8)
    offset = len(bitmap)
    for i in range(0, len(bits), 8):
        byte = 0
        for bit in bits[i : i + 8]:
            byte = byte << 1 | bit
        bitmap.append(byte)
    return {
        "w": w,
        "h": h,
        "x_offset": check_range(left - size, -128, 127, "x offset", ch),
        "y_offset": check_range(upper - size * 2, -128, 127, "y offset", ch),
        "advance": advance,
        "offset": offset,
    }


def build_font(font, size: int) -> dict:
    bitmap = bytearray()
    glyphs = [
        build_glyph(font, chr(code), size, bitmap) for code in range(FIRST, LAST + 1)
    ]
    inked = [g for g in glyphs if g["h"]]
    above = max(-g["y_offset"] for g in inked)
    below = max(g["y_offset"] + g["h"] for g in inked)
    return {
        "first": FIRST,
        "last": LAST,
        "y_advance": check_range(above + below, 1, 255, "line height", "line"),
        "glyphs": glyphs,
        "bitmap": bytes(bitmap),
    }


def unpack(bitmap: bytes, glyph: dict) -> list[list[int]]:
    """The glyph's ink as rows of 0 and 1."""
    w, h = glyph["w"], glyph["h"]
    bits = [bitmap[glyph["offset"] + i // 8] >> (7 - i % 8) & 1 for i in range(w * h)]
    return [bits[y * w : (y + 1) * w] for y in range(h)]


def c_bytes(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 24):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
    return "\n".join(rows)


def c_header(name: str, font: dict, source: str) -> str:
    guard = f"GENERATED_{name.upper()}_H"
    out = [
        f"/* Generated by tools/make_badge_font.py from {source}. Do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "/* Needs lgfx::GFXfont declared first (main.cpp includes M5Unified). */",
        f"static uint8_t {name}_bitmap[] = {{",
        c_bytes(font["bitmap"]) if font["bitmap"] else "  0,",
        "};",
        f"static lgfx::GFXglyph {name}_glyphs[] = {{",
    ]
    for g in font["glyphs"]:
        out.append(
            f"  {{{g['offset']},{g['w']},{g['h']},{g['advance']},"
            f"{g['x_offset']},{g['y_offset']}}},"
        )
    out.append("};")
    out.append(
        f"static const lgfx::GFXfont {name}_font({name}_bitmap, {name}_glyphs, "
        f"{font['first']}, {font['last']}, {font['y_advance']});"
    )
    out.append(f"#endif /* {guard} */")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("ttf", type=Path)
    parser.add_argument("--name", required=True, help="C identifier prefix")
    parser.add_argument("--size", type=int, required=True, help="the font's pixel size")
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        font = build_font(open_font(args.ttf, args.size), args.size)
    except ValueError as err:
        print(f"make_badge_font: {err}", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(c_header(args.name, font, args.ttf.name))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
