"""Rasterise a TrueType font into the C header that the Xft stand-in draws from.

The device has no font renderer, so each size is drawn here once, as 8-bit
coverage for printable ASCII (32 to 126). The structures are declared in
firmware/src/x11shim/include/xft_font.h and handed to the shim with
xshim_set_font.

Run with: uv run tools/make_font_atlas.py firmware/assets/fonts/SpecialElite-Regular.ttf \\
    --name special_elite --sizes 12,16,20,24 -o special_elite.h
"""

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
MIN_SIZE = 4
MAX_EXTENT = 255
DIGITS = "0123456789"


def build_glyph(font, ch: str, size: int, alpha: bytearray, ink: bool = True) -> dict:
    """Render ch tightly cropped, appending its coverage to alpha. Without ink
    the glyph keeps its advance and draws nothing."""
    advance = round(font.getlength(ch))
    if not ink:
        return {"w": 0, "h": 0, "left": 0, "top": 0, "advance": advance, "offset": 0}
    canvas = Image.new("L", (size * 3, size * 3), 0)
    ImageDraw.Draw(canvas).text((size, size * 2), ch, fill=255, font=font, anchor="ls")
    box = canvas.getbbox()
    if box is None:
        return {"w": 0, "h": 0, "left": 0, "top": 0, "advance": advance, "offset": 0}
    left, upper, right, lower = box
    if right - left > MAX_EXTENT or lower - upper > MAX_EXTENT:
        raise ValueError(
            f"{ch!r} at {size} pixels is {right - left} by {lower - upper}: "
            f"a glyph is at most {MAX_EXTENT} pixels each way (the table holds bytes)"
        )
    if not (-128 <= left - size <= 127 and -128 <= size * 2 - upper <= 127):
        raise ValueError(
            f"{ch!r} at {size} pixels sits more than 127 pixels from its pen "
            "(the table holds signed bytes)"
        )
    cropped = canvas.crop(box)
    offset = len(alpha)
    alpha += cropped.tobytes()
    return {
        "w": right - left,
        "h": lower - upper,
        "left": left - size,
        "top": size * 2 - upper,
        "advance": advance,
        "offset": offset,
    }


def build_font(
    path: Path, sizes: list[int], digits_from: int | None = None
) -> list[dict]:
    """Sizes from `digits_from` up draw only the digits: a big size is for a big
    number, and every other glyph at that size would be flash for nothing."""
    result = []
    for size in sizes:
        if size < MIN_SIZE:
            raise ValueError(f"size {size} is below {MIN_SIZE} pixels")
        try:
            font = ImageFont.truetype(str(path), size)
        except OSError as err:
            raise ValueError(f"{path}: not a usable font ({err})") from err
        ascent, descent = font.getmetrics()
        alpha = bytearray()
        glyphs = [
            build_glyph(
                font,
                chr(code),
                size,
                alpha,
                ink=digits_from is None or size < digits_from or chr(code) in DIGITS,
            )
            for code in range(FIRST, LAST + 1)
        ]
        result.append(
            {
                "pixel_size": size,
                "ascent": ascent,
                "descent": descent,
                "glyphs": glyphs,
                "alpha": bytes(alpha),
            }
        )
    return result


def c_bytes(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 24):
        rows.append("  " + ",".join(f"{b}" for b in data[i : i + 24]) + ",")
    return "\n".join(rows)


def c_header(name: str, font: list[dict], source: str) -> str:
    guard = f"GENERATED_{name.upper()}_H"
    out = [
        f"/* Generated by tools/make_font_atlas.py from {source}. Do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        '#include "x11shim/xft_font.h"',
        "",
    ]
    for size in font:
        px = size["pixel_size"]
        out.append(f"static const unsigned char {name}_alpha_{px}[] = {{")
        out.append(c_bytes(size["alpha"]) if size["alpha"] else "  0,")
        out.append("};")
        out.append(f"static const XshimGlyph {name}_glyphs_{px}[] = {{")
        for g in size["glyphs"]:
            out.append(
                f"  {{{g['w']},{g['h']},{g['left']},{g['top']},"
                f"{g['advance']},{g['offset']}}},"
            )
        out.append("};")
    out.append(f"static const XshimFontSize {name}_sizes[] = {{")
    for size in font:
        px = size["pixel_size"]
        out.append(
            f"  {{{px},{size['ascent']},{size['descent']},"
            f"{name}_glyphs_{px},{name}_alpha_{px}}},"
        )
    out.append("};")
    out.append(f"static const XshimFont {name}_font = {{{len(font)}, {name}_sizes}};")
    out.append(f"#endif /* {guard} */")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("ttf", type=Path)
    parser.add_argument("--name", required=True, help="C identifier prefix")
    parser.add_argument("--sizes", required=True, help="comma-separated pixel sizes")
    parser.add_argument(
        "--digits-from",
        type=int,
        help="sizes at or above this many pixels hold only the digits",
    )
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        sizes = sorted({int(s) for s in args.sizes.split(",")})
        font = build_font(args.ttf, sizes, args.digits_from)
    except ValueError as err:
        print(f"make_font_atlas: {err}", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(c_header(args.name, font, args.ttf.name))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
